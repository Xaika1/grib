import argparse
import random
import sqlite3
import time
from datetime import UTC, datetime, timedelta

REGIONS = ["Москва", "Санкт-Петербург", "Казань", "Новосибирск", "Екатеринбург"]
STATUSES = ["new", "paid", "shipped", "cancelled"]
QUEUES = ["orders", "emails", "payments"]

SCHEMA = [
    """CREATE TABLE IF NOT EXISTS orders (
        id INTEGER PRIMARY KEY {autoinc},
        created_at TIMESTAMP NOT NULL,
        amount NUMERIC(10, 2) NOT NULL,
        status VARCHAR(20) NOT NULL,
        region VARCHAR(50) NOT NULL
    )""",
    "CREATE INDEX IF NOT EXISTS ix_orders_created_at ON orders (created_at)",
    """CREATE TABLE IF NOT EXISTS queue_state (
        name VARCHAR(50) PRIMARY KEY,
        size INTEGER NOT NULL,
        updated_at TIMESTAMP NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS online_users (
        id INTEGER PRIMARY KEY,
        users INTEGER NOT NULL,
        updated_at TIMESTAMP NOT NULL
    )""",
]


def now() -> datetime:
    return datetime.now(UTC).replace(tzinfo=None, microsecond=0)


def ts(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%d %H:%M:%S")


def daily_factor(dt: datetime) -> float:
    hour = (dt.hour + 3) % 24
    return 0.2 + 0.8 * max(0.0, 1 - abs(hour - 14) / 10)


class Store:
    def __init__(self, args):
        if args.sqlite:
            self.conn = sqlite3.connect(args.sqlite)
            self.ph = "?"
            self.autoinc = "AUTOINCREMENT"
            self.pg = False
        else:
            import psycopg

            for attempt in range(30):
                try:
                    self.conn = psycopg.connect(args.url)
                    break
                except psycopg.OperationalError:
                    if attempt == 29:
                        raise
                    time.sleep(2)
            self.ph = "%s"
            self.autoinc = "GENERATED BY DEFAULT AS IDENTITY"
            self.pg = True

    def q(self, sql: str) -> str:
        return sql.replace("?", self.ph)

    def execute(self, sql: str, params=()):
        cur = self.conn.cursor()
        cur.execute(self.q(sql), params)
        return cur

    def setup(self, history_days: int) -> None:
        for stmt in SCHEMA:
            self.execute(stmt.format(autoinc=self.autoinc))
        self.conn.commit()
        count = self.execute("SELECT COUNT(*) FROM orders").fetchone()[0]
        if count:
            return
        print(f"Заполняю историю заказов за {history_days} дн…")
        rows = []
        t = now() - timedelta(days=history_days)
        end = now()
        while t < end:
            if random.random() < daily_factor(t):
                rows.append(self.order_row(t))
            t += timedelta(seconds=random.randint(20, 100))
        cur = self.conn.cursor()
        cur.executemany(self.q("INSERT INTO orders (created_at, amount, status, region) VALUES (?, ?, ?, ?)"), rows)
        for name in QUEUES:
            self.execute("INSERT INTO queue_state (name, size, updated_at) VALUES (?, ?, ?)", (name, random.randint(0, 20), ts(now())))
        self.execute("INSERT INTO online_users (id, users, updated_at) VALUES (1, ?, ?)", (random.randint(50, 150), ts(now())))
        self.conn.commit()
        print(f"Добавлено заказов: {len(rows)}")

    @staticmethod
    def order_row(dt: datetime) -> tuple:
        status = random.choices(STATUSES, weights=[2, 5, 6, 1])[0]
        return (ts(dt), round(random.lognormvariate(7.5, 0.6), 2), status, random.choice(REGIONS))

    def tick(self, interval: float) -> None:
        t = now()
        if random.random() < min(1.0, interval / 60 * daily_factor(t)):
            self.execute("INSERT INTO orders (created_at, amount, status, region) VALUES (?, ?, ?, ?)", self.order_row(t))
        for name, size in self.execute("SELECT name, size FROM queue_state").fetchall():
            jump = random.choice([0] * 9 + [25])
            new_size = max(0, size + random.randint(-4, 4) + jump - (10 if size > 40 else 0))
            self.execute("UPDATE queue_state SET size = ?, updated_at = ? WHERE name = ?", (new_size, ts(t), name))
        users = self.execute("SELECT users FROM online_users WHERE id = 1").fetchone()[0]
        target = int(300 * daily_factor(t))
        users = max(0, users + random.randint(-8, 8) + (target - users) // 10)
        self.execute("UPDATE online_users SET users = ?, updated_at = ? WHERE id = 1", (users, ts(t)))
        self.conn.commit()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument("--sqlite", help="путь к файлу SQLite")
    target.add_argument("--url", help="строка подключения PostgreSQL")
    parser.add_argument("--interval", type=float, default=5, help="период обновления, с")
    parser.add_argument("--days", type=int, default=7, help="глубина истории, дней")
    parser.add_argument("--once", action="store_true", help="только создать таблицы и историю")
    args = parser.parse_args()

    store = Store(args)
    store.setup(args.days)
    if args.once:
        return
    print("Генерирую данные. Ctrl+C — остановить.")
    try:
        while True:
            store.tick(args.interval)
            time.sleep(args.interval)
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
